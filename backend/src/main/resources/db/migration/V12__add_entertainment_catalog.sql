CREATE TABLE entertainment_work (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_code varchar(32) NOT NULL,
    category varchar(16) NOT NULL,
    title varchar(64) NOT NULL,
    summary varchar(1000) NOT NULL,
    creator_name varchar(64) NOT NULL,
    collection_name varchar(64),
    duration_seconds integer NOT NULL,
    release_year smallint NOT NULL,
    language varchar(32) NOT NULL,
    region varchar(32) NOT NULL,
    enabled boolean NOT NULL DEFAULT true,
    sort_order integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uk_entertainment_work_code UNIQUE (work_code),
    CONSTRAINT uk_entertainment_work_category_title UNIQUE (category, title),
    CONSTRAINT uk_entertainment_work_category_sort UNIQUE (category, sort_order),
    CONSTRAINT ck_entertainment_work_category CHECK (category IN ('VIDEO', 'MUSIC')),
    CONSTRAINT ck_entertainment_work_duration CHECK (duration_seconds > 0),
    CONSTRAINT ck_entertainment_work_release_year CHECK (release_year BETWEEN 1900 AND 2100),
    CONSTRAINT ck_entertainment_work_sort CHECK (sort_order > 0)
);

CREATE INDEX idx_entertainment_work_category_enabled
    ON entertainment_work (category, enabled, sort_order, work_code);

CREATE TABLE entertainment_work_genre (
    work_id bigint NOT NULL REFERENCES entertainment_work(id) ON DELETE CASCADE,
    genre varchar(32) NOT NULL,
    position smallint NOT NULL,
    PRIMARY KEY (work_id, genre),
    CONSTRAINT uk_entertainment_work_genre_position UNIQUE (work_id, position),
    CONSTRAINT ck_entertainment_work_genre_position CHECK (position > 0)
);

CREATE INDEX idx_entertainment_work_genre_lookup
    ON entertainment_work_genre (genre, work_id);

